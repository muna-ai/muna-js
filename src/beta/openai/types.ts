import type { Image } from "../../types"

/**
 * Reasoning effort for reasoning models.
 */
export type ChatCompletionReasoningEffort = "none" | "minimal" | "low" | "medium" | "high" | "xhigh";

/**
 * Tool choice mode.
 */
export type ChatCompletionToolChoice = "auto" | "none";

export interface ChatCompletion {
    /**
     * The object type, which is always `chat.completion`.
     */
    object: "chat.completion";
    /**
     * A unique identifier for the chat completion.
     */
    id: string;
    /**
     * The model used for the chat completion.
     */
    model: string;
    /**
     * A list of chat completion choices. Can be more than one if `n` is greater
     * than 1.
     */
    choices: Array<ChatCompletion.Choice>;
    /**
     * The Unix timestamp (in seconds) of when the chat completion was created.
     */
    created: number;
    /**
     * Usage statistics for the completion request.
     */
    usage?: ChatCompletion.Usage;
}

export interface ChatCompletionChunk {
    /**
     * The object type, which is always `chat.completion.chunk`.
     */
    object: "chat.completion.chunk";
    /**
     * A unique identifier for the chat completion. Each chunk has the same ID.
     */
    id: string;
    /**
     * The model to generate the completion.
     */
    model: string;
    /**
     * A list of chat completion choices. Can contain more than one elements if `n` is
     * greater than 1. Can also be empty for the last chunk if you set
     * `stream_options: {"include_usage": true}`.
     */
    choices: Array<ChatCompletionChunk.Choice>;
    /**
     * The Unix timestamp (in seconds) of when the chat completion was created. Each
     * chunk has the same timestamp.
     */
    created: number;
    /**
     * Usage statistics for the completion request.
     */
    usage?: ChatCompletion.Usage | null;
}

export namespace ChatCompletion {

    export interface Choice {
        /**
         * The index of the choice in the list of choices.
         */
        index: number;
        /**
         * A chat completion message generated by the model.
         */
        message: Message;
        /**
         * The reason the model stopped generating tokens. This will be `stop` if the model
         * hit a natural stop point or a provided stop sequence, `length` if the maximum
         * number of tokens specified in the request was reached, `content_filter` if
         * content was omitted due to a flag from our content filters, `tool_calls` if the
         * model called a tool, or `function_call` (deprecated) if the model called a
         * function.
         */
        finish_reason: "stop" | "length" | "tool_calls" | "content_filter" | "function_call";
        /**
         * Log probability information for the choice.
         */
        logprobs?: null;
    }

    /**
     * Message returned in a chat completion choice.
     */
    export interface Message {
        /**
         * The role of the author of this message.
         */
        role: "assistant" | "user" | "system" | "developer" | "tool";
        /**
         * The contents of the message.
         */
        content: string | null;
        /**
         * Reasoning contents of the message, before the final answer.
         * Follows the DeepSeek convention for reasoning models.
         */
        reasoning_content?: string;
        /**
         * Tool calls generated by the model.
         */
        tool_calls?: ChatCompletionMessageFunctionToolCall[];
    }

    export interface Usage {
        /**
         * Number of tokens in the generated completion.
         */
        completion_tokens: number;
        /**
         * Number of tokens in the prompt.
         */
        prompt_tokens: number;
        /**
         * Total number of tokens used in the request (prompt + completion).
         */
        total_tokens: number;
        /**
         * Breakdown of tokens used in the prompt.
         */
        prompt_tokens_details?: Usage.PromptTokensDetails | null;
        /**
         * Breakdown of tokens used in the completion.
         */
        completion_tokens_details?: Usage.CompletionTokensDetails | null;
    }

    export namespace Usage {

        export interface PromptTokensDetails {
            /**
             * Audio input tokens present in the prompt.
             */
            audio_tokens?: number | null;
            /**
             * The unadjusted number of prompt tokens written to cache.
             */
            cache_write_tokens?: number | null;
            /**
             * Cached tokens present in the prompt.
             */
            cached_tokens?: number | null;
        }

        export interface CompletionTokensDetails {
            /**
             * Tokens generated by the model for reasoning.
             */
            reasoning_tokens?: number | null;
        }
    }
}

export namespace ChatCompletionChunk {

    export interface Choice {
        /**
         * The index of the choice in the list of choices.
         */
        index: number;
        /**
         * A chat completion delta generated by streamed model responses.
         */
        delta: Choice.Delta | null;
        /**
         * The reason the model stopped generating tokens. This will be `stop` if the model
         * hit a natural stop point or a provided stop sequence, `length` if the maximum
         * number of tokens specified in the request was reached, `content_filter` if
         * content was omitted due to a flag from our content filters, `tool_calls` if the
         * model called a tool, or `function_call` (deprecated) if the model called a
         * function.
         */
        finish_reason?: "stop" | "length" | "tool_calls" | "content_filter" | "function_call" | null;
        /**
         * Log probability information for the choice.
         */
        logprobs?: null;
    }

    export namespace Choice {

        export interface Delta {
            /**
             * The role of the author of this message.
             */
            role?: "developer" | "system" | "user" | "assistant" | "tool";
            /**
             * The contents of the chunk message.
             */
            content?: string | null;
            /**
             * Reasoning contents of the message delta, before the final answer.
             * Follows the DeepSeek convention for reasoning models.
             */
            reasoning_content?: string | null;
            /**
             * Streamed tool call fragments, accumulated by `index`.
             */
            tool_calls?: Delta.ToolCall[] | null;
        }

        export namespace Delta {

            export interface ToolCall {
                /**
                 * Index of the tool call that this fragment belongs to.
                 */
                index: number;
                /**
                 * The ID of the tool call.
                 * This is only present on the first fragment of a tool call.
                 */
                id?: string | null;
                /**
                 * The type of the tool.
                 */
                type?: "function" | null;
                /**
                 * Function name and argument fragment.
                 */
                function?: {
                    name?: string | null;
                    arguments?: string | null;
                } | null;
            }
        }
    }
}

/**
 * Chat message.
 */
export interface ChatCompletionMessage {
    /**
     * The role of the author of this message.
     */
    role: "assistant" | "user" | "system" | "developer" | "tool";
    /**
     * The contents of the message.
     */
    content: string | ChatCompletionContentPart[] | null;
    /**
     * Reasoning contents of a previous assistant message.
     */
    reasoning_content?: string | null;
    /**
     * Tool calls generated by a previous assistant message.
     */
    tool_calls?: ChatCompletionMessageFunctionToolCall[] | null;
    /**
     * Tool call that this tool message responds to.
     */
    tool_call_id?: string | null;
}

export interface ChatCompletionContentPartText {
    type: "text";
    /**
     * The text content.
     */
    text: string;
}

export interface ChatCompletionContentPartImage {
    type: "image_url";
    image_url: {
        /**
         * Either a URL of the image or the base64 encoded image data.
         */
        url: string;
        /**
         * Specifies the detail level of the image.
         */
        detail?: "auto" | "low" | "high" | null;
    };
}

export interface ChatCompletionContentPartInputAudio {
    type: "input_audio";
    input_audio: {
        /**
         * Base64 encoded audio data.
         */
        data: string;
        /**
         * The format of the encoded audio data.
         */
        format: "wav" | "mp3";
    };
}

export interface ChatCompletionContentPartFile {
    type: "file";
    file: {
        /**
         * The base64 encoded file data.
         */
        file_data?: string | null;
        /**
         * The ID of an uploaded file to use as input.
         */
        file_id?: string | null;
        /**
         * The name of the file.
         */
        filename?: string | null;
    };
}

export interface ChatCompletionContentPartRefusal {
    type: "refusal";
    /**
     * The refusal message generated by the model.
     */
    refusal: string;
}

export type ChatCompletionContentPart =
    ChatCompletionContentPartText       |
    ChatCompletionContentPartImage      |
    ChatCompletionContentPartInputAudio |
    ChatCompletionContentPartFile       |
    ChatCompletionContentPartRefusal;

export interface FunctionDefinition {
    /**
     * The name of the function to be called.
     */
    name: string;
    /**
     * A description of what the function does, used by the model to choose when and how to call the function.
     */
    description?: string | null;
    /**
     * The parameters the function accepts, described as a JSON Schema object.
     */
    parameters?: Record<string, unknown> | null;
    /**
     * Whether to enable strict schema adherence when generating the function call.
     */
    strict?: boolean | null;
}

export interface ChatCompletionFunctionTool {
    type: "function";
    function: FunctionDefinition;
}

export interface ChatCompletionMessageFunctionToolCall {
    /**
     * The ID of the tool call.
     */
    id: string;
    type: "function";
    function: {
        /**
         * The name of the function to call.
         */
        name: string;
        /**
         * The arguments to call the function with, as a JSON-encoded string.
         */
        arguments: string;
    };
}


/**
 * Represents an embedding vector returned by embedding endpoint.
 */
export interface Embedding {
    /**
     * The object type, which is always "embedding".
     */
    object: "embedding";
    /**
     * The embedding vector as number array or base64 string..
     */
    embedding: number[] | string;
    /**
     * The index of the embedding in the list of embeddings.
     */
    index: number;
}

export interface CreateEmbeddingResponse {
    /**
     * The object type, which is always "list".
     */
    object: "list";
    /**
     * The name of the model used to generate the embedding.
     */
    model: string;
    /**
     * The list of embeddings generated by the model.
     */
    data: Embedding[];
    /**
     * The usage information for the request.
     */
    usage: CreateEmbeddingResponse.Usage;
}

export namespace CreateEmbeddingResponse {

    /**
     * The usage information for the request.
     */
    export interface Usage {
        /**
         * The number of tokens used by the prompt.
         */
        prompt_tokens: number;
        /**
         * The total number of tokens used by the request.
         */
        total_tokens: number;
    }
}

export interface Transcription {
    /**
     * Transcribed text.
     */
    text: string;
    /**
     * Token usage statistics for the request.
     */
    usage: Transcription.Usage;
}

export namespace Transcription {

    /**
     * Usage statistics for models that track token usage.
     */
    export interface TokenUsage {
        /**
         * Usage type. Always `tokens`.
         */
        type: "tokens";
        /**
         * Number of input tokens used for this request.
         */
        input_tokens: number;
        /**
         * Details about the input tokens used for this request.
         */
        input_token_details: {
            /**
             * Number of text tokens used for this request.
             */
            text_tokens: number;
            /**
             * Number of audio tokens used for this request.
             */
            audio_tokens: number;
        };
        /**
         * Number of output tokens generated.
         */
        output_tokens: number;
        /**
         * Total number of tokens used.
         */
        total_tokens: number;
    }

    /**
     * Usage statistics for models that track audio input duration.
     */
    export interface DurationUsage {
        /**
         * Usage type. Always `duration`.
         */
        type: "duration";
        /**
         * Duration of the input audio in seconds.
         */
        seconds: number;
    }

    /**
     * The usage information for the request.
     */
    export type Usage = TokenUsage | DurationUsage;
}

export interface ImageResponse {
    /**
     * The list of generated images.
     */
    data?: ImageResponse.ImageData[];
    /**
     * The background parameter used for the image generation.
     */
    background?: "transparent" | "opaque";
    /**
     * The Unix timestamp (in seconds) of when the image was created.
     */
    created: number;
    /**
     * Token usage information for the image generation.
     */
    usage?: ImageResponse.Usage;
}

export namespace ImageResponse {

    export interface ImageData {
        /**
         * Base64-encoded JSON of the generated image.
         */
        b64_json?: string;
        /**
         * Generated image in memory.
         */
        image?: Image;
    }

    export interface Usage {
        /**
         * The number of tokens (images and text) in the input prompt.
         */
        input_tokens: number;
        /**
         * The number of output tokens generated by the model.
         */
        output_tokens: number;
        /**
         * The total number of tokens used for the image generation.
         */
        total_tokens: number;
        /**
         * Detailed breakdown of input tokens.
         */
        input_tokens_details: Usage.InputTokensDetails;
        /**
         * Detailed breakdown of output tokens.
         */
        output_tokens_details?: Usage.OutputTokensDetails;
    }

    export namespace Usage {

        export interface InputTokensDetails {
            /**
             * The number of image tokens in the input prompt.
             */
            image_tokens: number;
            /**
             * The number of text tokens in the input prompt.
             */
            text_tokens: number;
        }

        export interface OutputTokensDetails {
            /**
             * The number of image output tokens generated by the model.
             */
            image_tokens: number;
            /**
             * The number of text output tokens generated by the model.
             */
            text_tokens: number;
        }
    }
}
